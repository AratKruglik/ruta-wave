const root = document.documentElement;
const ATTRIBUTES = [["data-i18n-alt", "alt"], ["data-i18n-label", "aria-label"], ["data-i18n-content", "content"]];
const originals = new WeakMap();

function original(element, name, current) {
  if (!originals.has(element)) originals.set(element, {});
  return originals.get(element)[name] ??= current;
}

function store(key, value) {
  try { localStorage.setItem(key, value); } catch {}
}

function stored(key) {
  try { return localStorage.getItem(key); } catch { return null; }
}

function applyLanguage(language) {
  const uk = language === "uk";
  root.lang = uk ? "uk" : "en";
  for (const element of document.querySelectorAll("[data-i18n]")) {
    const english = original(element, "html", element.innerHTML);
    element.innerHTML = uk ? UK[element.dataset.i18n] ?? english : english;
  }
  for (const [selector, attribute] of ATTRIBUTES) {
    for (const element of document.querySelectorAll(`[${selector}]`)) {
      const english = original(element, attribute, element.getAttribute(attribute));
      element.setAttribute(attribute, uk ? UK[element.getAttribute(selector)] ?? english : english);
    }
  }
  const toggle = document.getElementById("language");
  toggle.textContent = uk ? "ENG" : "УКР";
  toggle.lang = uk ? "en" : "uk";
  toggle.setAttribute("aria-label", uk ? "English" : "Українська");
}

const systemDark = matchMedia("(prefers-color-scheme: dark)");

function applyTheme() {
  const theme = root.dataset.theme ?? (systemDark.matches ? "dark" : "light");
  root.classList.toggle("dark", theme === "dark");
  document.getElementById("theme").setAttribute("aria-pressed", String(theme === "dark"));
}

const language = stored("language") ?? (navigator.languages ?? [navigator.language]).find(l => /^(uk|en)\b/i.test(l))?.slice(0, 2).toLowerCase();
applyLanguage(language);
applyTheme();
systemDark.addEventListener("change", applyTheme);

document.getElementById("language").addEventListener("click", () => {
  const next = root.lang === "uk" ? "en" : "uk";
  store("language", next);
  applyLanguage(next);
});

document.getElementById("theme").addEventListener("click", () => {
  root.dataset.theme = root.classList.contains("dark") ? "light" : "dark";
  store("theme", root.dataset.theme);
  applyTheme();
});

const observer = new IntersectionObserver(entries => {
  for (const entry of entries) {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      observer.unobserve(entry.target);
    }
  }
}, { rootMargin: "0px 0px -8% 0px" });
document.querySelectorAll(".reveal").forEach(element => observer.observe(element));
